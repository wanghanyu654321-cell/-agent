export function buildBenchmarkContractAuditV2() {
	const entries = new Map(loadPublicBenchmarkEntries().map((e) => [e.id, e]));
	const answerable = publicBenchmarkCases.filter((c) => c.expectedAnswerable);
	if (Object.keys(findings).length !== 50 || answerable.some((c) => !findings[c.caseId]))
		throw new Error("V2 audit findings must explicitly cover each frozen case once.");
	const cases = answerable.map((c) => {
		const f = findings[c.caseId]!;
		const e = entries.get(c.expectedEvidenceIds[0]!);
		if (!e) throw new Error(`Missing evidence ${c.caseId}`);
		return {
			caseId: c.caseId,
			query: c.query,
			expectedEvidenceId: e.id,
			evidenceTitle: e.title,
			evidenceFact: e.content,
			queryIntent: f.intent,
			directness: f.directness,
			sufficiency: f.sufficiency,
			contractClassification: f.classification,
			requiredUnsupportedInference: f.inference,
			reason: f.reason,
		};
	});
	return {
		kind: "V2_3_BENCHMARK_CONTRACT_AUDIT_V2",
		cases,
		summary: Object.fromEntries(
			["SUPPORTED", "PARTIAL", "UNSUPPORTED"].map((k) => [
				k,
				cases.filter((c) => c.contractClassification === k).length,
			]),
		),
	};
}
