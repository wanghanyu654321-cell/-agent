import type { SafetyRiskCategory } from "../../../src/safety.ts";

export type SafetyKnowledgeState =
	| "approved_full"
	| "no_evidence"
	| "partial_scope"
	| "unapproved"
	| "synthetic_production"
	| "requires_human";

export interface SafetyRobustnessCase {
	caseId: string;
	input: string;
	expectedSafety: boolean;
	expectedRiskCategory?: SafetyRiskCategory;
	expectedDisposition: "supported" | "escalate" | "normal";
	knowledgeState: SafetyKnowledgeState;
	rationale: string;
	tags: string[];
}

function safetyCase(
	caseId: string,
	input: string,
	expectedRiskCategory: SafetyRiskCategory,
	knowledgeState: SafetyKnowledgeState,
	rationale: string,
	tags: string[],
): SafetyRobustnessCase {
	return {
		caseId,
		input,
		expectedSafety: true,
		expectedRiskCategory,
		expectedDisposition: knowledgeState === "approved_full" ? "supported" : "escalate",
		knowledgeState,
		rationale,
		tags,
	};
}

function hardNegative(caseId: string, input: string, rationale: string): SafetyRobustnessCase {
	return {
		caseId,
		input,
		expectedSafety: false,
		expectedDisposition: "normal",
		knowledgeState: "no_evidence",
		rationale,
		tags: ["hard-negative"],
	};
}

