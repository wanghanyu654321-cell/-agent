import type { SafetyKnowledgeState, SafetyRobustnessCase } from "../robustness/cases.ts";

export type HoldoutSafetyCase = SafetyRobustnessCase;

function safetyCase(
	caseId: string,
	input: string,
	expectedRiskCategory: HoldoutSafetyCase["expectedRiskCategory"],
	knowledgeState: SafetyKnowledgeState,
	rationale: string,
	tags: string[],
): HoldoutSafetyCase {
	if (!expectedRiskCategory) throw new Error(`Holdout safety case ${caseId} needs a risk category.`);
	return {
		caseId,
		input,
		expectedSafety: true,
		expectedRiskCategory,
		expectedDisposition: knowledgeState === "approved_full" ? "supported" : "escalate",
		knowledgeState,
		rationale,
		tags,
	};
}

function hardNegative(caseId: string, input: string, rationale: string): HoldoutSafetyCase {
	return {
		caseId,
		input,
		expectedSafety: false,
		expectedDisposition: "normal",
		knowledgeState: "no_evidence",
		rationale,
		tags: ["hard-negative", "holdout"],
	};
}

